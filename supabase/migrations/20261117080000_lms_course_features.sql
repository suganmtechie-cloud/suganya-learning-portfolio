-- Extend the existing Learning Studio model with LMS course delivery.
-- A learning_path is the course; a learning_module is a course module.
-- Supabase Auth remains the only identity/password store.

create table if not exists public.learning_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  created_at timestamptz not null default now()
);

alter table public.learning_paths
  add column if not exists category_id bigint
  references public.learning_categories(id) on delete set null;

create table if not exists public.lessons (
  id uuid primary key default gen_random_uuid(),
  module_id uuid not null references public.learning_modules(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200),
  content_type text not null default 'text'
    check (content_type in ('video', 'pdf', 'text', 'link')),
  content_url text,
  body text not null default '',
  duration_minutes integer check (duration_minutes is null or duration_minutes >= 0),
  position integer not null default 0 check (position >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (module_id, position)
);

create table if not exists public.course_enrollments (
  id uuid primary key default gen_random_uuid(),
  learner_id uuid not null references auth.users(id) on delete cascade,
  learning_path_id uuid not null references public.learning_paths(id) on delete cascade,
  enrolled_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (learner_id, learning_path_id)
);

create table if not exists public.lesson_progress (
  learner_id uuid not null references auth.users(id) on delete cascade,
  lesson_id uuid not null references public.lessons(id) on delete cascade,
  status text not null default 'not_started'
    check (status in ('not_started', 'in_progress', 'completed')),
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (learner_id, lesson_id)
);

create index if not exists lessons_module_position_idx
  on public.lessons(module_id, position);
create index if not exists course_enrollments_learner_idx
  on public.course_enrollments(learner_id);
create index if not exists lesson_progress_learner_idx
  on public.lesson_progress(learner_id);

alter table public.learning_categories enable row level security;
alter table public.lessons enable row level security;
alter table public.course_enrollments enable row level security;
alter table public.lesson_progress enable row level security;

create policy "Authenticated users read learning categories"
on public.learning_categories for select to authenticated
using (true);

create policy "Path owners manage lessons"
on public.lessons for all to authenticated
using (exists (
  select 1
  from public.learning_modules m
  join public.learning_paths p on p.id = m.learning_path_id
  where m.id = module_id and p.owner_id = (select auth.uid())
))
with check (exists (
  select 1
  from public.learning_modules m
  join public.learning_paths p on p.id = m.learning_path_id
  where m.id = module_id and p.owner_id = (select auth.uid())
));

create policy "Enrolled learners read lessons in published paths"
on public.lessons for select to authenticated
using (exists (
  select 1
  from public.learning_modules m
  join public.learning_paths p on p.id = m.learning_path_id
  join public.course_enrollments e on e.learning_path_id = p.id
  where m.id = module_id
    and p.status = 'published'
    and e.learner_id = (select auth.uid())
));

create policy "Learners read own enrollments and instructors read their course enrollments"
on public.course_enrollments for select to authenticated
using (
  learner_id = (select auth.uid())
  or exists (
    select 1 from public.learning_paths p
    where p.id = learning_path_id and p.owner_id = (select auth.uid())
  )
);

create policy "Learners enroll themselves in published paths"
on public.course_enrollments for insert to authenticated
with check (
  learner_id = (select auth.uid())
  and exists (
    select 1 from public.learning_paths p
    where p.id = learning_path_id and p.status = 'published'
  )
);

create policy "Learners update their own enrollment completion"
on public.course_enrollments for update to authenticated
using (learner_id = (select auth.uid()))
with check (learner_id = (select auth.uid()));

create policy "Learners manage only their own lesson progress"
on public.lesson_progress for all to authenticated
using (learner_id = (select auth.uid()))
with check (
  learner_id = (select auth.uid())
  and exists (
    select 1
    from public.lessons l
    join public.learning_modules m on m.id = l.module_id
    join public.course_enrollments e on e.learning_path_id = m.learning_path_id
    where l.id = lesson_id and e.learner_id = (select auth.uid())
  )
);
